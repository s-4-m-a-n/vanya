export const LOCALES = { en: "English", hi: "हिन्दी", es: "Español" } as const;
export type Locale = keyof typeof LOCALES;
const MESSAGES: Record<Locale, Messages> = { en, hi, es };

export function isLocale(value: string | undefined | null): value is Locale {
  return !!value && value in LOCALES;
}

export function translate(
  locale: Locale,
  key: MessageKey,
  vars: Record<string, string | number> = {},
): string {
  const template = MESSAGES[locale][key] ?? en[key];
  const values: Record<string, string | number> = { app: APP_NAME, ...vars };
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

/** Look up a key that is only known at runtime (error codes, statuses), with a fallback. */
export function translateDynamic(locale: Locale, key: string, fallback: MessageKey): string {
  return key in en ? translate(locale, key as MessageKey) : translate(locale, fallback);
}

export const LocaleContext = createContext<Locale>("en");

export function useT() {
  const locale = useContext(LocaleContext);
  const t = (key: MessageKey, vars?: Record<string, string | number>) =>
    translate(locale, key, vars);
  t.dynamic = (key: string, fallback: MessageKey) => translateDynamic(locale, key, fallback);
  t.locale = locale;
  return t;
}
